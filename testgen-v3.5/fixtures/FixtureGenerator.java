package com.testgen.fixtures;

import com.squareup.javapoet.ClassName;
import com.squareup.javapoet.CodeBlock;
import com.squareup.javapoet.FieldSpec;
import com.squareup.javapoet.JavaFile;
import com.squareup.javapoet.MethodSpec;
import com.squareup.javapoet.ParameterizedTypeName;
import com.squareup.javapoet.TypeSpec;

import java.nio.file.Files;
import java.nio.file.Path;
import javax.lang.model.element.Modifier;

/**
 * TG-BOILERDET emission pass, fixture half: writes one testsupport fixture per detected facade,
 * shaped like the lab's LoggerFixture/ConfigFixture (delegate swap in install, mandatory restore
 * in tearDown). Reflection stays INSIDE the fixture so emitted test code carries none, and no
 * mockStatic of the facade ever exists — the delegate swap cannot collide.
 *
 * Skips emission when the target project already has a fixture of the same name.
 */
public final class FixtureGenerator {

    static final String FIXTURE_PACKAGE = "testsupport";

    private static final ClassName MOCKITO = ClassName.get("org.mockito", "Mockito");
    private static final ClassName REFLECT_FIELD = ClassName.get("java.lang.reflect", "Field");
    private static final ClassName LINKED_MAP = ClassName.get("java.util", "LinkedHashMap");
    private static final ClassName MAP = ClassName.get("java.util", "Map");

    private FixtureGenerator() {}

    public static String fixtureSimpleName(SMCFixtureScanner.Facade facade) {
        return facade.facadeClass().getSimpleName() + "Fixture";
    }

    /** Writes the fixture unless one already exists; returns its ClassName either way. */
    public static ClassName write(SMCFixtureScanner.Facade facade, Path testSourceRoot) throws Exception {
        String simpleName = fixtureSimpleName(facade);
        ClassName fixtureName = ClassName.get(FIXTURE_PACKAGE, simpleName);
        Path target = testSourceRoot.resolve(FIXTURE_PACKAGE).resolve(simpleName + ".java");
        if (Files.exists(target)) {
            System.out.println("SKIP fixture (exists): " + target);
            return fixtureName;
        }

        JavaFile.builder(FIXTURE_PACKAGE,
                        buildType(facade, simpleName).addModifiers(Modifier.PUBLIC).build())
                .skipJavaLangImports(true)
                .addFileComment("AUTO-GENERATED by testgen FixtureGenerator (TG-BOILERDET)")
                .build()
                .writeTo(testSourceRoot);
        System.out.println("Wrote " + FIXTURE_PACKAGE + "." + simpleName);
        return fixtureName;
    }

    /**
     * Inline mode (BOILERPLATE_INLINE): the SAME fixture as a private static nested class of the
     * test class - self-contained file, no shared testsupport code.
     */
    public static TypeSpec nestedType(SMCFixtureScanner.Facade facade) {
        return buildType(facade, fixtureSimpleName(facade))
                .addModifiers(Modifier.PRIVATE, Modifier.STATIC)
                .build();
    }

    private static TypeSpec.Builder buildType(SMCFixtureScanner.Facade facade, String simpleName) {
        TypeSpec.Builder fixture = TypeSpec.classBuilder(simpleName)
                .addModifiers(Modifier.FINAL)   // visibility added by each emission mode
                .addJavadoc("AUTO-GENERATED delegate-swap fixture for $L.\n"
                                + "Lab play: swap the singleton's delegates, restore in tearDown — no mockStatic.\n"
                                + "Reflection is contained here so the test class carries none.\n",
                        facade.facadeClass().getName());

        fixture.addField(FieldSpec.builder(
                        ParameterizedTypeName.get(MAP, ClassName.get(String.class), ClassName.get(Object.class)),
                        "originals", Modifier.PRIVATE, Modifier.FINAL)
                .initializer("new $T<>()", LINKED_MAP)
                .build());

        for (SMCFixtureScanner.DelegateField d : facade.delegates()) {
            fixture.addField(FieldSpec.builder(handleType(d), handleName(d), Modifier.PRIVATE).build());
            fixture.addMethod(MethodSpec.methodBuilder(handleName(d))
                    .addModifiers(Modifier.PUBLIC)
                    .returns(handleType(d))
                    .addStatement("return $L", handleName(d))
                    .build());
        }

        fixture.addMethod(installMethod(facade));
        fixture.addMethod(restoreMethod(facade));
        return fixture;
    }

    /** install(): capture each original delegate, swap in the test double. */
    private static MethodSpec installMethod(SMCFixtureScanner.Facade facade) {
        MethodSpec.Builder b = MethodSpec.methodBuilder("install")
                .addModifiers(Modifier.PUBLIC)
                .addException(Exception.class)
                .addJavadoc("Swaps every delegate for a test double; restore() afterwards is mandatory.\n");

        ClassName facadeName = ClassName.get(facade.facadeClass());
        if (facade.needsInstance()) {
            b.addStatement("$T target = $T.$L($L)", facadeName, facadeName,
                    facade.accessor().getName(), accessorArgs(facade));
        }
        for (SMCFixtureScanner.DelegateField d : facade.delegates()) {
            String fieldVar = d.name() + "Field";
            b.addStatement("$T $L = $T.class.getDeclaredField($S)",
                    REFLECT_FIELD, fieldVar, facadeName, d.name());
            b.addStatement("$L.setAccessible(true)", fieldVar);
            b.addStatement("originals.put($S, $L.get($L))", d.name(), fieldVar, targetOf(d));
            if (d.mapShaped()) {
                b.addStatement("$L = new $T<>(($T<?, ?>) originals.get($S))",
                        handleName(d), LINKED_MAP, MAP, d.name());
                for (String key : seededKeys(facade)) {
                    b.addStatement("$L.put($S, $S)", handleName(d), key,
                            com.config.Config.SEEDED_PLACEHOLDER_VALUE);
                }
            } else if (seedable(d)) {
                b.addStatement("$L = new $T()", handleName(d), rawType(d));
                for (String key : seededKeys(facade)) {
                    b.addStatement("$L.setProperty($S, $S)", handleName(d), key,
                            com.config.Config.SEEDED_PLACEHOLDER_VALUE);
                }
            } else {
                b.addStatement("$L = $T.mock($T.class)", handleName(d), MOCKITO, rawType(d));
            }
            b.addStatement("$L.set($L, $L)", fieldVar, targetOf(d), handleName(d));
        }
        return b.build();
    }

    /** restore(): put every original back — the delegates are JVM-global state. */
    private static MethodSpec restoreMethod(SMCFixtureScanner.Facade facade) {
        MethodSpec.Builder b = MethodSpec.methodBuilder("restore")
                .addModifiers(Modifier.PUBLIC)
                .addException(Exception.class);

        ClassName facadeName = ClassName.get(facade.facadeClass());
        if (facade.needsInstance()) {
            b.addStatement("$T target = $T.$L($L)", facadeName, facadeName,
                    facade.accessor().getName(), accessorArgs(facade));
        }
        for (SMCFixtureScanner.DelegateField d : facade.delegates()) {
            String fieldVar = d.name() + "Field";
            b.beginControlFlow("if (originals.containsKey($S))", d.name());
            b.addStatement("$T $L = $T.class.getDeclaredField($S)",
                    REFLECT_FIELD, fieldVar, facadeName, d.name());
            b.addStatement("$L.setAccessible(true)", fieldVar);
            b.addStatement("$L.set($L, originals.get($S))", fieldVar, targetOf(d), d.name());
            b.endControlFlow();
        }
        return b.build();
    }

    /** Map delegates keep their runtime shape via a live LinkedHashMap copy; others get a mock. */
    private static com.squareup.javapoet.TypeName handleType(SMCFixtureScanner.DelegateField d) {
        if (d.mapShaped()) {
            return ParameterizedTypeName.get(LINKED_MAP,
                    ClassName.get(Object.class), ClassName.get(Object.class));
        }
        return ClassName.get(d.type());
    }

    private static ClassName rawType(SMCFixtureScanner.DelegateField d) {
        return ClassName.get(d.type());
    }

    private static String handleName(SMCFixtureScanner.DelegateField d) {
        return d.name() + (d.mapShaped() ? "Values" : "Mock");
    }

    private static String targetOf(SMCFixtureScanner.DelegateField d) {
        return d.staticField() ? "null" : "target";
    }

    /** Class params get the fixture's own class literal; String params a fixed token. */
    private static CodeBlock accessorArgs(SMCFixtureScanner.Facade facade) {
        CodeBlock.Builder args = CodeBlock.builder();
        boolean first = true;
        for (Class<?> p : facade.accessor().getParameterTypes()) {
            if (!first) {
                args.add(", ");
            }
            first = false;
            if (p == Class.class) {
                args.add("$L.class", fixtureSimpleName(facade));
            } else {
                args.add("$S", "testgen");
            }
        }
        return args.build();
    }

    /**
     * TWEAK-POINT (CONFIG_PAYLOAD=SEEDED): a delegate is seedable when it has a public no-arg
     * constructor and a setProperty(String, Object) seam. Anything else falls back to a mock.
     */
    private static boolean seedable(SMCFixtureScanner.DelegateField d) {
        if (!"SEEDED".equals(com.config.Config.CONFIG_PAYLOAD)) {
            return false;
        }
        try {
            d.type().getConstructor();
            d.type().getMethod("setProperty", String.class, Object.class);
            return true;
        } catch (Throwable t) {
            return false;
        }
    }

    /**
     * TWEAK-POINT (CONFIG_PAYLOAD=SEEDED): key discovery. Scans every main-source file for string
     * literals on lines that mention the facade's simple name or its accessor, keeping literals
     * that look like config keys (dotted or underscored, no spaces). Over-collection is harmless -
     * an extra key just carries the placeholder value.
     */
    private static java.util.List<String> seededKeys(SMCFixtureScanner.Facade facade) {
        if (!"SEEDED".equals(com.config.Config.CONFIG_PAYLOAD)) {
            return java.util.List.of();
        }
        java.util.regex.Pattern literal = java.util.regex.Pattern.compile("\"([A-Za-z0-9_.]*[._][A-Za-z0-9_.]*)\"");
        java.util.LinkedHashSet<String> keys = new java.util.LinkedHashSet<>();
        String simple = facade.facadeClass().getSimpleName();
        String accessor = facade.accessor().getName();
        try (var files = java.nio.file.Files.walk(com.config.Config.mainSourceRoot())) {
            for (java.nio.file.Path p : files.filter(f -> f.toString().endsWith(".java")).toList()) {
                for (String line : java.nio.file.Files.readAllLines(p)) {
                    if (!line.contains(simple) && !line.contains(accessor + "(")) {
                        continue;
                    }
                    java.util.regex.Matcher m = literal.matcher(line);
                    while (m.find()) {
                        keys.add(m.group(1));
                    }
                }
            }
        } catch (Throwable ignored) { }
        return new java.util.ArrayList<>(keys);
    }
}
